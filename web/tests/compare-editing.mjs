async function inObsidian(before, keys) {
  const { text, anchor, focus } = parse(before)
  // Keys reach Obsidian's editor only while its window has the focus.
  await app.bringToFront()
  await app.evaluate(async ([value, a, f]) => {
    const editor = window.app.workspace.getLeavesOfType('markdown')[0].view.editor
    // A footnote's or a link's hover editor left behind stays the active editor (commands go to
    // it): the note's own editor is the active one again.
    document.querySelectorAll('.popover').forEach((popover) => popover.remove())
    window.app.workspace._activeEditor = null
    // The text goes in as a 'set' change outside the history: Obsidian renumbers the lists a change
    // is in, and setValue would renumber the starting text itself.
    const cm = editor.cm
    const Transaction = cm.state.update({}).constructor
    cm.dispatch({ changes: { from: 0, to: cm.state.doc.length, insert: value }, userEvent: 'set', annotations: [Transaction.addToHistory.of(false)] })
    // The caret first, so the line shows its Markdown before the selection is made: a selection
    // made on a line drawn without its marks takes the hidden marks in (live preview's atomic
    // ranges), which no one selecting in the editor gets.
    window.app.commands.executeCommandById('editor:unfold-all')
    // The scenario counts characters; the editor's offsets are UTF-16 units (an emoji is two).
    const units = (index) => [...value].slice(0, index).join('').length
    editor.setSelection(editor.offsetToPos(units(f)))
    await new Promise((resolve) => setTimeout(resolve, 50))
    editor.setSelection(editor.offsetToPos(units(a)), editor.offsetToPos(units(f)))
    editor.focus()
    document.querySelector('.workspace-leaf.mod-active .cm-content')?.focus()
  }, [text, anchor, focus])
  const focused = await app.evaluate(() => document.activeElement?.classList.contains('cm-content') ?? false)
  if (!focused) throw new Error('Obsidian\'s editor does not take the focus (is its window behind another?)')
  await app.waitForTimeout(150)
  // The clipboard is the system's: Electron's, from Obsidian's own window.
  await act(
    app,
    keys,
    (text) => app.evaluate((text) => window.require('electron').clipboard.writeText(text), text),
    (id) => app.evaluate((id) => window.app.commands.executeCommandById(id), id),
  )
  await app.waitForTimeout(200)
  return app.evaluate(() => {
    const editor = window.app.workspace.getLeavesOfType('markdown')[0].view.editor
    const value = editor.getValue()
    const anchor = editor.posToOffset(editor.getCursor('anchor'))
    const head = editor.posToOffset(editor.getCursor('head'))
    // Offsets in UTF-16 units to characters.
    const chars = (offset) => [...value.slice(0, offset)].length
    return { value, anchor: chars(anchor), head: chars(head) }
  })
}

